#!/usr/bin/env python3
"""Generate a synthetic but realistic AD-style export for testing Vanguard.

This file is what you upload to the web UI to see real findings without
touching a domain controller. It is clearly labelled as synthetic.

Usage:
    python tools/make_demo_export.py
    python tools/make_demo_export.py -o /tmp/lab.json --size large
"""
from __future__ import annotations
import argparse
import json
import random
import sys
from pathlib import Path


def build_graph(seed: int = 7, size: str = "medium") -> dict:
    rng = random.Random(seed)
    nodes, edges = [], []

    def add(nid, name, ntype):
        nodes.append({"id": nid, "name": name, "type": ntype, "label": name})

    def edge(src, dst, rel):
        edges.append({"source": src, "target": dst, "relationship": rel})

    # --- Fixed named accounts ------------------------------------------------
    add("u:alice",  "alice.contractor",  "User")
    add("u:bob",    "bob.helpdesk",      "User")
    add("u:carol",  "carol.svc.backup",  "User")
    add("u:dave",   "dave.intern",       "User")
    add("u:admin",  "dana.admin",        "User")

    add("g:helpdesk",   "Helpdesk",          "Group")
    add("g:serverops",  "Server Operators",  "Group")
    add("g:backupops",  "Backup Operators",  "Group")
    add("g:itadmins",   "IT Admins",         "Group")
    add("g:domainadm",  "Domain Admins",     "Group")

    add("c:ws01", "LAB-WS01", "Computer")
    add("c:srv01","LAB-SRV01","Computer")
    add("c:dc01", "LAB-DC01", "Computer")

    # --- Base memberships ----------------------------------------------------
    edge("u:alice", "g:helpdesk",  "MemberOf")
    edge("u:bob",   "g:helpdesk",  "MemberOf")
    edge("u:admin", "g:domainadm", "MemberOf")
    edge("c:dc01",  "g:domainadm", "MemberOf")

    # --- Path A: alice -> Helpdesk -> AdminTo SRV01 -> GenericAll ServerOps -> Domain Admins
    edge("g:helpdesk",  "c:srv01",     "AdminTo")
    edge("c:srv01",     "g:serverops", "GenericAll")
    edge("g:serverops", "g:domainadm", "MemberOf")

    # --- Path B: carol svc backup -> Backup Operators -> WriteDacl -> Domain Admins
    edge("u:carol",     "g:backupops", "MemberOf")
    edge("g:backupops", "g:domainadm", "WriteDacl")

    # --- Path C: dave intern -> IT Admins -> ForceChangePassword -> dana.admin -> Domain Admins
    edge("u:dave",    "g:itadmins",  "MemberOf")
    edge("g:itadmins","u:admin",     "ForceChangePassword")

    # --- A few extra edges for noise -----------------------------------------
    edge("u:bob",   "c:ws01",  "CanRDP")
    edge("c:ws01",  "g:itadmins","MemberOf")

    # --- Optionally pad the graph -------------------------------------------
    if size == "large":
        for i in range(400):
            nid = f"u:bulk{i:04d}"
            add(nid, f"bulk.user{i:04d}", "User")
            edge(nid, "g:helpdesk", "MemberOf")
        for i in range(120):
            cid = f"c:bulk{i:04d}"
            add(cid, f"BULK-WS-{i:04d}", "Computer")
            edge(cid, "g:itadmins", "MemberOf")

    return {
        "schema_version": "synthetic-1",
        "source_domain": "SYNTHETIC.LAB (not a real domain)",
        "nodes": nodes,
        "edges": edges,
        "notes": [
            "SYNTHETIC DATA. Generated by tools/make_demo_export.py.",
            "Not collected from any real Active Directory domain.",
            "For UI testing only. Do not represent these findings as evidence.",
        ],
    }


def main(argv=None):
    p = argparse.ArgumentParser(description="Generate a synthetic AD-style export for Vanguard.")
    p.add_argument("-o", "--output", default="vanguard-demo-export.json",
                   help="output path (default: ./vanguard-demo-export.json)")
    p.add_argument("--seed", type=int, default=7)
    p.add_argument("--size", choices=["medium", "large"], default="medium")
    args = p.parse_args(argv)

    graph = build_graph(seed=args.seed, size=args.size)
    out = Path(args.output)
    out.write_text(json.dumps(graph, indent=2), encoding="utf-8")
    print(f"Wrote {len(graph['nodes'])} nodes / {len(graph['edges'])} edges to {out}")
    print("Upload this file to the Vanguard web UI.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
